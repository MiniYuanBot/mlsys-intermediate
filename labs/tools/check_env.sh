#!/usr/bin/env bash
# The per-lab environment verdict: one line per item, with functional probes.
#   bash tools/check_env.sh --lab 2     # only what lab2 needs (non-cumulative)
#   bash tools/check_env.sh --lab all   # every lab (default)
# [ OK ] works   [WARN] usable but differs from the pins / only needed by stage R
# [FAIL] required and broken (a `fix:` line follows)   [ -- ] optional or not on this platform
# Exit code: 0 no FAIL, 1 at least one FAIL, 2 usage error / wrong shell.
# Paste the output into the "环境" section of your lab report.
set -uo pipefail

cd "$(dirname "$0")/.."
. tools/env-versions.env
RUST=$(sed -n 's/^RUST=//p' tools/formatter-versions.env | tr -d '\r')
VENV="${MLSYS_VENV:-$HOME/venvs/mlsys}"
MODELS="${MLSYS_MODELS:-$HOME/models}"
PY="$VENV/bin/python"
# Non-login shells (CI, `wsl -- bash -c`) skip ~/.bashrc; look in the default places too.
export PATH="/usr/local/cuda/bin:$HOME/.cargo/bin:$PATH"

LAB=all
case "${1:-}" in
    "") ;;
    --lab) LAB="${2:-}" ;;
    *) LAB=x ;;
esac

# BEGIN LAB TABLE (generated by: python tools/lab_meta.py --table; keep in sync)
lab_entry() {
    case $1 in
        1) comps="gpu:R cuda:R" models="" ;;
        2) comps="gpu cuda" models="" ;;
        3) comps="gpu cuda torch" models="" ;;
        4) comps="gpu:R torch:R hf:R cargo" models="Qwen3-0.6B:R Qwen3-1.7B:R" ;;
        5) comps="gpu:R torch:R hf:R cargo" models="Qwen3-0.6B:R" ;;
        6) comps="gpu torch" models="" ;;
        7) comps="gpu cuda" models="" ;;
        8) comps="cargo" models="" ;;
        9) comps="gpu:R cuda:R" models="" ;;
        *) return 1 ;;
    esac
}
ALL_LABS="1 2 3 4 5 6 7 8 9"
# END LAB TABLE

if [[ $LAB == all ]]; then labs=$ALL_LABS; else labs=$LAB; fi
for n in $labs; do
    lab_entry "$n" 2> /dev/null || {
        echo "usage: bash tools/check_env.sh [--lab N|all]   (N = 1-9)" >&2
        exit 2
    }
done
case $(uname -s) in
    MINGW* | MSYS* | CYGWIN*)
        echo "This is Git Bash/MSYS on Windows; this script does not run here." >&2
        echo "  native Windows (CPU parts):  powershell -ExecutionPolicy Bypass -File tools\\check_env.ps1 -Lab $LAB" >&2
        echo "  WSL2 (everything):           wsl -d Ubuntu-24.04, then: bash tools/check_env.sh --lab $LAB" >&2
        exit 2
        ;;
    Darwin) OS=mac ;;
    *) OS=linux ;;
esac
FIX="bash tools/setup_env.sh --lab $LAB"
fail=0
warns=0

ok() { printf '  [ OK ]  %-20s %s\n' "$1" "$2"; }
warn() {
    printf '  [WARN]  %-20s %s\n' "$1" "$2"
    [[ -n ${3:-} ]] && printf '          %-20s fix: %s\n' "" "$3"
    warns=$((warns + 1))
}
bad() { # bad <name> <message> [fix]
    printf '  [FAIL]  %-20s %s\n' "$1" "$2"
    printf '          %-20s fix: %s\n' "" "${3:-$FIX}"
    fail=1
}
opt() { printf '  [ -- ]  %-20s %s\n' "$1" "$2"; }
check() { # check <req|soft|opt> <name> <command...>
    local level=$1 name=$2
    shift 2
    local out
    if out=$("$@" 2>&1); then
        ok "$name" "$(echo "$out" | tail -1)"
    else
        case $level in
            req) bad "$name" "$(echo "$out" | tail -1)" ;;
            soft) warn "$name" "$(echo "$out" | tail -1) (only stage R needs it)" "$FIX" ;;
            *) opt "$name" "not available (optional): $(echo "$out" | tail -1)" ;;
        esac
    fi
}
pyver() { # pyver <level> <name> <dist name> <pinned version>
    local got
    if got=$("$PY" -c "import importlib.metadata as m; print(m.version('$3'))" 2>&1); then
        if [[ $got == "$4" || $got == "$4+"* ]]; then
            ok "$2" "$got"
        else
            warn "$2" "$got (pinned $4)" "$FIX --repin"
        fi
    elif [[ $1 == soft ]]; then
        warn "$2" "not installed (only stage R needs it)" "$FIX"
    else
        bad "$2" "not installed in $VENV"
    fi
}
level_of() { [[ $1 == *:R ]] && echo soft || echo req; }

# Per component: req if any selected lab needs it outside stage R, else soft. Plain
# variables (LV_<component>), not an associative array: macOS ships bash 3.2.
MODEL_LEVEL=" "
for n in $labs; do
    lab_entry "$n"
    for c in $comps; do
        var="LV_${c%:R}"
        [[ ${!var:-} == req ]] || printf -v "$var" '%s' "$(level_of "$c")"
    done
    for m in $models; do
        name=${m%:R}
        if [[ $(level_of "$m") == req ]]; then
            MODEL_LEVEL=${MODEL_LEVEL/ $name=soft / }
            [[ $MODEL_LEVEL == *" $name=req "* ]] || MODEL_LEVEL+="$name=req "
        elif [[ $MODEL_LEVEL != *" $name="* ]]; then
            MODEL_LEVEL+="$name=soft "
        fi
    done
done
has() {
    local var="LV_$1"
    [[ -n ${!var:-} ]]
}
lvl() {
    local var="LV_$1"
    echo "${!var:-opt}"
}

# --- items -------------------------------------------------------------------------------
item_platform() {
    local where=$OS
    [[ $OS == linux ]] && grep -qi microsoft /proc/version 2> /dev/null && where=wsl
    ok "platform" "$where ($(uname -sr)), venv $VENV"
    for n in $labs; do
        [[ -f lab$n/exercise.py ]] || opt "lab$n" "registered in tools/lab_meta.py; labs/lab$n not in this checkout yet"
    done
}
item_python() {
    # The usual failure: `python script.py` runs the system Python, which has no numpy.
    local exe got
    for exe in python python3; do
        got=$(command -v "$exe" || echo "not found")
        if [[ $got == "$VENV/bin/$exe" ]]; then
            ok "$exe on PATH" "$got"
        elif [[ -x $PY ]]; then
            bad "$exe on PATH" "$got is not the course venv" \
                "open a new terminal and cd into the repo (direnv activates it), or run: mlsys"
        else
            bad "$exe on PATH" "venv $VENV does not exist"
        fi
    done
}
item_base() {
    pyver req numpy numpy "$NUMPY"
    pyver req matplotlib matplotlib "$MATPLOTLIB"
    pyver req pytest pytest "$PYTEST"
}
item_pins() {
    local want got stamp="$VENV/.mlsys-pins"
    want=$(grep -E '^[A-Z_][A-Z0-9_]*=' tools/env-versions.env | tr -d '\r' | { sha256sum 2> /dev/null || shasum -a 256; } | cut -d' ' -f1)
    if [[ ! -f $stamp ]]; then
        warn "pins stamp" "$stamp missing (venv not created by this setup_env)" "$FIX"
    elif got=$(head -1 "$stamp" | cut -d' ' -f1) && [[ $got == "$want" ]]; then
        ok "pins stamp" "${want:0:16}… matches tools/env-versions.env"
    else
        warn "pins stamp" "venv pinned ${got:0:16}…, this checkout ${want:0:16}…" "$FIX --repin"
    fi
    local sibling=../../mlsys-foundations/labs/tools/env-versions.env
    if [[ -f $sibling ]]; then
        if diff <(grep -E '^[A-Z_][A-Z0-9_]*=' "$sibling" | tr -d '\r') \
            <(grep -E '^[A-Z_][A-Z0-9_]*=' tools/env-versions.env | tr -d '\r') > /dev/null; then
            ok "foundations pins" "same as ../mlsys-foundations (shared venv is consistent)"
        else
            warn "foundations pins" "../mlsys-foundations pins differ; the shared venv fits only one" \
                "align both env-versions.env files, or set MLSYS_VENV per repository"
        fi
    else
        opt "foundations pins" "no sibling ../mlsys-foundations checkout"
    fi
}
item_cxx() {
    local tmp out family
    tmp=$(mktemp -d)
    cat > "$tmp/hello.cpp" << 'CPP'
#include <cstdio>
#include <optional>
#include <string_view>
int main() { std::optional<std::string_view> s = "C++17 ok"; std::printf("%s\n", s->data()); }
CPP
    local cxx=${CXX:-c++}
    if out=$("$cxx" -std=c++17 -O2 "$tmp/hello.cpp" -o "$tmp/hello" 2>&1 && "$tmp/hello"); then
        family=$("$cxx" --version 2> /dev/null | head -1)
        ok "C++17 compiler" "$out: $(command -v "$cxx") ($family)"
    else
        bad "C++17 compiler" "$cxx failed to build a C++17 program: $(echo "$out" | tail -1)"
    fi
    rm -rf "$tmp"
    check opt "cmake" bash -c 'cmake --version | head -1'
    check opt "git" bash -c 'git --version'
    if [[ $OS == mac || $OS == linux ]]; then
        if command -v direnv > /dev/null; then
            ok "direnv" "$(direnv version) (activates the venv inside the repo)"
        else
            warn "direnv" "not installed: activate by hand with \`mlsys\`" "$FIX"
        fi
    fi
}
item_gpu() {
    local l
    l=$(lvl gpu)
    if [[ $OS == mac ]]; then
        opt "GPU" "macOS: CUDA stages run in WSL2/Linux"
        return
    fi
    check "$l" "GPU (driver)" bash -c "nvidia-smi --query-gpu=name,driver_version,memory.total --format=csv,noheader 2>/dev/null || /usr/lib/wsl/lib/nvidia-smi --query-gpu=name,driver_version,memory.total --format=csv,noheader"
}
item_cuda() {
    local l got tmp out
    l=$(lvl cuda)
    if [[ $OS == mac ]]; then
        opt "nvcc" "macOS: CUDA stages run in WSL2/Linux"
        return
    fi
    if got=$(nvcc --version 2>&1 | grep release); then
        if [[ $got == *"release $CUDA,"* ]]; then ok nvcc "$got"; else warn nvcc "$got (pinned $CUDA)"; fi
    else
        if [[ $l == req ]]; then bad nvcc "nvcc not found"; else warn nvcc "nvcc not found (only stage R needs it)" "$FIX"; fi
        return
    fi
    tmp=$(mktemp -d)
    cat > "$tmp/k.cu" << 'CU'
#include <cstdio>
__global__ void add(int *x) { x[threadIdx.x] += threadIdx.x; }
int main() {
    int h[32] = {0}, *d = nullptr;
    if (cudaMalloc(&d, sizeof h) != cudaSuccess) { std::printf("cudaMalloc failed\n"); return 1; }
    cudaMemcpy(d, h, sizeof h, cudaMemcpyHostToDevice);
    add<<<1, 32>>>(d);
    cudaError_t e = cudaMemcpy(h, d, sizeof h, cudaMemcpyDeviceToHost);
    if (e != cudaSuccess || h[31] != 31) { std::printf("kernel failed: %s\n", cudaGetErrorString(e)); return 1; }
    std::printf("compiled and ran a kernel\n");
}
CU
    if out=$(nvcc -std=c++17 -arch="${MLSYS_CUDA_ARCH:-native}" "$tmp/k.cu" -o "$tmp/k" 2>&1 && "$tmp/k" 2>&1); then
        ok "nvcc kernel" "$out (-arch=${MLSYS_CUDA_ARCH:-native})"
    elif [[ $l == req ]]; then
        bad "nvcc kernel" "$(echo "$out" | tail -1)" "check the driver (nvidia-smi) and see setup.md"
    else
        warn "nvcc kernel" "$(echo "$out" | tail -1) (only stage R needs it)"
    fi
    rm -rf "$tmp"
    check opt "ncu / nsys" bash -c "ncu --version | tail -1 && nsys --version"
}
item_torch() {
    local l
    l=$(lvl torch)
    pyver "$l" torch torch "$TORCH"
    if [[ $OS == linux ]] && has gpu; then
        pyver opt triton triton "$TRITON"
        local gl=$l
        [[ $(lvl gpu) == soft ]] && gl=soft
        check "$gl" "torch + CUDA" "$PY" -c "import torch; assert torch.cuda.is_available(), 'torch.cuda.is_available() is False (CPU wheel or driver)'; x=torch.randn(512,512,device='cuda'); (x@x).sum().item(); print('matmul ok, CUDA', torch.version.cuda, torch.cuda.get_device_name())"
    fi
}
item_inductor() {
    check req "Inductor (cpu)" "$PY" tools/doctor.py --compile-probe --device cpu
    if [[ $OS == linux ]]; then
        check req "Inductor (cuda)" "$PY" tools/doctor.py --compile-probe --device cuda
    fi
}
item_hf() {
    local l
    l=$(lvl hf)
    pyver "$l" transformers transformers "$TRANSFORMERS"
    pyver "$l" safetensors safetensors "$SAFETENSORS"
    pyver "$l" huggingface_hub huggingface_hub "$HF_HUB"
}
item_cargo() {
    local got
    local rustc
    if got=$(cargo --version 2>&1) && rustc=$(rustc --version 2>&1); then
        if [[ $rustc == "rustc $RUST "* ]]; then
            ok "cargo / rustc" "$got / $rustc"
        else
            warn "cargo / rustc" "$got / $rustc (pinned $RUST)" "$FIX"
        fi
    else
        bad "cargo / rustc" "cargo not found (also looked in ~/.cargo/bin)"
    fi
}
item_models() {
    local entry name l
    for entry in $MODEL_LEVEL; do
        name=${entry%=*} l=${entry#*=}
        check "$l" "$name" "$PY" -c "
import json, pathlib
d = pathlib.Path('$MODELS/$name')
assert (d / 'config.json').is_file(), f'{d}/config.json missing'
assert (d / 'tokenizer.json').is_file(), 'tokenizer.json missing'
w = sum(f.stat().st_size for f in d.glob('*.safetensors'))
assert w > 0, 'no *.safetensors (incomplete download)'
cfg = json.loads((d / 'config.json').read_text())
print(cfg.get('model_type'), 'layers', cfg.get('num_hidden_layers'), f'{w/2**30:.2f} GiB in {d}')"
    done
}

echo "== lab $LAB environment ($(uname -s), venv $VENV)"
item_platform
item_python
item_base
item_pins
item_cxx
has gpu && item_gpu
has cuda && item_cuda
has torch && item_torch
[[ " $labs " == *" 3 "* ]] && item_inductor
has hf && item_hf
has cargo && item_cargo
[[ -n ${MODEL_LEVEL// /} ]] && item_models

echo
if [[ $fail == 0 ]]; then
    if ((warns)); then echo "All required items OK ($warns warning(s): see [WARN] lines)."; else echo "All required items OK."; fi
else
    echo "Some required items FAILED (fix commands above)."
fi
exit $fail
