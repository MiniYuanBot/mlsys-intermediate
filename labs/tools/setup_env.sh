#!/usr/bin/env bash
# Installs the base environment plus what ONE lab needs (labs are independent, nothing
# accumulates), at the versions pinned in tools/env-versions.env.
#   bash tools/setup_env.sh --lab 5              # base + Rust
#   bash tools/setup_env.sh --lab 4 --no-models  # base + Rust + PyTorch + HF, skip Qwen3
#   bash tools/setup_env.sh --lab all            # union of every lab
#   bash tools/setup_env.sh --lab 2 --repin      # allow changing a venv set up with other pins
#
# Base: C++17 compiler, cmake, git, direnv, venv ${MLSYS_VENV:-~/venvs/mlsys} with
# numpy/matplotlib/pytest. Per-lab components come from the LAB TABLE below, which must
# match tools/lab_meta.py (tools/test_platform.py checks it).
# Platforms: WSL2 Ubuntu 24.04 (main) and native Linux get everything; macOS gets the CPU
# parts (CUDA steps are skipped with a note). Native Windows: tools/setup_env.ps1.
# The venv is shared with mlsys-foundations; $VENV/.mlsys-pins records the pin hash, and a
# different hash stops this script unless --repin is given.
# Safe to re-run: every step skips what is already there. sudo is used only for apt.
set -euo pipefail

cd "$(dirname "$0")/.."
LABS_ROOT=$PWD
. tools/env-versions.env
RUST=$(sed -n 's/^RUST=//p' tools/formatter-versions.env | tr -d '\r')

VENV="${MLSYS_VENV:-$HOME/venvs/mlsys}"
MODELS="${MLSYS_MODELS:-$HOME/models}"
LAB=""
WITH_MODELS=1
REPIN=0
usage() {
    echo "usage: bash tools/setup_env.sh --lab N|all [--no-models] [--repin]   (N = 1-9)" >&2
    exit 2
}
while (($#)); do
    case $1 in
        --lab)
            LAB=${2:-}
            shift 2 || usage
            ;;
        --no-models) WITH_MODELS=0 && shift ;;
        --repin) REPIN=1 && shift ;;
        -h | --help) usage ;;
        *) usage ;;
    esac
done

# BEGIN LAB TABLE (generated by: python tools/lab_meta.py --table; keep in sync)
lab_entry() {
    case $1 in
        1) comps="gpu:R cuda:R" models="" ;;
        2) comps="gpu cuda" models="" ;;
        3) comps="gpu cuda torch" models="" ;;
        4) comps="gpu:R torch:R hf:R cargo" models="Qwen3-0.6B:R Qwen3-1.7B:R" ;;
        5) comps="gpu:R torch:R hf:R cargo" models="Qwen3-0.6B:R" ;;
        6) comps="gpu torch" models="" ;;
        7) comps="gpu cuda" models="" ;;
        8) comps="cargo" models="" ;;
        9) comps="gpu:R cuda:R" models="" ;;
        *) return 1 ;;
    esac
}
ALL_LABS="1 2 3 4 5 6 7 8 9"
# END LAB TABLE

[[ -n $LAB ]] || usage
if [[ $LAB == all ]]; then labs=$ALL_LABS; else labs=$LAB; fi
COMPONENTS=" " MODEL_LIST=""
for n in $labs; do
    lab_entry "$n" 2> /dev/null || usage
    for c in $comps; do [[ $COMPONENTS == *" ${c%:R} "* ]] || COMPONENTS+="${c%:R} "; done
    for m in $models; do [[ " $MODEL_LIST " == *" ${m%:R} "* ]] || MODEL_LIST+="${m%:R} "; done
done
want() { [[ $COMPONENTS == *" $1 "* ]]; }
if [[ $LAB != all && ! -f lab$LAB/exercise.py ]]; then
    echo "note: lab$LAB is registered in tools/lab_meta.py but labs/lab$LAB does not exist yet;"
    echo "      installing its dependencies anyway."
fi

case $(uname -s) in
    Linux) OS=linux RC="$HOME/.bashrc" SHELL_NAME=bash ;;
    Darwin) OS=mac RC="$HOME/.zshrc" SHELL_NAME=zsh ;;
    MINGW* | MSYS* | CYGWIN*)
        echo "This is Git Bash/MSYS on Windows; this script does not run here." >&2
        echo "  CPU parts, native Windows (PowerShell, in labs\\):" >&2
        echo "    powershell -ExecutionPolicy Bypass -File tools\\setup_env.ps1 -Lab $LAB" >&2
        echo "  Everything incl. CUDA, in WSL2 (run: wsl -d Ubuntu-24.04):" >&2
        echo "    bash tools/setup_env.sh --lab $LAB" >&2
        exit 2
        ;;
    *)
        echo "Unsupported system $(uname -s): see setup.md." >&2
        exit 2
        ;;
esac

step() { printf '\n\033[1;34m==> %s\033[0m\n' "$*"; }
add_line() { grep -qxF "$1" "$RC" 2> /dev/null || echo "$1" >> "$RC"; }
sha256() { if command -v sha256sum > /dev/null; then sha256sum; else shasum -a 256; fi | cut -d' ' -f1; }
PINS_HASH=$(grep -E '^[A-Z_][A-Z0-9_]*=' tools/env-versions.env | tr -d '\r' | sha256 || true)

echo "lab: $LAB   components:${COMPONENTS% }   models: ${MODEL_LIST:-none}"
if [[ $OS == mac ]] && { want cuda || want gpu; }; then
    echo "macOS: CUDA stages of lab $LAB are skipped (no NVIDIA GPU); run them in WSL2 or on Linux."
    echo "       The CPU parts and the rest of the environment are installed below."
fi

# Pins guard: the venv may be shared with mlsys-foundations or an older checkout.
STAMP="$VENV/.mlsys-pins"
if [[ -f $STAMP && $(head -1 "$STAMP" | cut -d' ' -f1) != "$PINS_HASH" && $REPIN == 0 ]]; then
    echo "The venv $VENV was set up with different pins (hash in $STAMP)." >&2
    echo "Your other checkout (e.g. ../mlsys-foundations) may use other versions. Either align" >&2
    echo "tools/env-versions.env, set MLSYS_VENV to a separate venv, or re-run with --repin." >&2
    exit 1
fi

step "system packages"
if [[ $OS == linux ]] && ! command -v apt-get > /dev/null; then
    # Not Debian/Ubuntu: we do not guess package names, only check the commands.
    missing=()
    for c in c++ make cmake git curl python3 direnv; do command -v "$c" > /dev/null || missing+=("$c"); done
    if ((${#missing[@]})); then
        echo "Install these with your package manager, then re-run: ${missing[*]}" >&2
        echo "(also the Python venv module and headers; for Rust labs pkg-config and OpenSSL headers)" >&2
        exit 1
    fi
    echo "all present"
    PYTHON=python3
elif [[ $OS == linux ]]; then
    # python3-dev: Triton/Inductor compile small C launchers against Python.h at runtime.
    pkgs=(build-essential cmake git curl python3-venv python3-dev direnv)
    want cargo && pkgs+=(pkg-config libssl-dev)
    missing=()
    for p in "${pkgs[@]}"; do dpkg -s "$p" > /dev/null 2>&1 || missing+=("$p"); done
    if ((${#missing[@]})); then
        echo "apt install ${missing[*]} (needs your sudo password)"
        sudo apt-get update
        sudo apt-get install -y "${missing[@]}"
    else
        echo "all present"
    fi
    PYTHON=python3
else
    xcode-select -p > /dev/null 2>&1 || {
        echo "Run 'xcode-select --install' first (C++ compiler), then re-run this script." >&2
        exit 1
    }
    command -v brew > /dev/null || {
        echo "Install Homebrew first (https://brew.sh), then re-run this script." >&2
        exit 1
    }
    for p in cmake git python@3.12 direnv; do brew list --versions "$p" > /dev/null || brew install "$p"; done
    PYTHON="$(brew --prefix)/bin/python3.12"
fi

if [[ $OS == linux ]] && want cuda; then
    step "CUDA toolkit $CUDA"
    if [[ -x /usr/local/cuda-$CUDA/bin/nvcc ]]; then
        echo "already installed: /usr/local/cuda-$CUDA"
    elif grep -qi microsoft /proc/version; then
        # The wsl-ubuntu repository ships the toolkit without a Linux GPU driver;
        # inside WSL the Windows driver is used. Never install a driver here.
        if ! dpkg -s cuda-keyring > /dev/null 2>&1; then
            tmp=$(mktemp -d)
            curl -fsSL -o "$tmp/cuda-keyring.deb" \
                https://developer.download.nvidia.com/compute/cuda/repos/wsl-ubuntu/x86_64/cuda-keyring_1.1-1_all.deb
            sudo dpkg -i "$tmp/cuda-keyring.deb"
            rm -rf "$tmp"
            sudo apt-get update
        fi
        sudo apt-get install -y "cuda-toolkit-${CUDA//./-}"
    elif [[ $(. /etc/os-release && echo "$ID $VERSION_ID") == "ubuntu 24.04" && $(uname -m) == x86_64 ]]; then
        # Native Ubuntu: cuda-toolkit-* contains no driver (unlike the `cuda` metapackage).
        if ! dpkg -s cuda-keyring > /dev/null 2>&1; then
            tmp=$(mktemp -d)
            curl -fsSL -o "$tmp/cuda-keyring.deb" \
                https://developer.download.nvidia.com/compute/cuda/repos/ubuntu2404/x86_64/cuda-keyring_1.1-1_all.deb
            sudo dpkg -i "$tmp/cuda-keyring.deb"
            rm -rf "$tmp"
            sudo apt-get update
        fi
        sudo apt-get install -y "cuda-toolkit-${CUDA//./-}"
    else
        echo "Install the CUDA $CUDA toolkit (toolkit only, keep your driver) from"
        echo "https://developer.nvidia.com/cuda-12-6-0-download-archive into /usr/local/cuda-$CUDA, then re-run."
    fi
fi
if [[ $OS == linux ]] && want gpu; then
    command -v nvidia-smi > /dev/null || [[ -x /usr/lib/wsl/lib/nvidia-smi ]] \
        || echo "WARNING: nvidia-smi not found. Install an NVIDIA driver that supports CUDA $CUDA (>= 560)."
fi

step "Python venv at $VENV"
if [[ ! -x $VENV/bin/python ]]; then
    mkdir -p "$(dirname "$VENV")"
    "$PYTHON" -m venv "$VENV"
    "$VENV/bin/python" -m pip install --upgrade pip
fi
pip_install() { "$VENV/bin/python" -m pip install --disable-pip-version-check "$@"; }
# Prints the requirements whose installed version differs from the pin (local +cu126/+cpu ok).
outdated() {
    "$VENV/bin/python" - "$@" << 'PY'
import importlib.metadata as m, sys
for req in sys.argv[1:]:
    name, want = req.split("==")
    try:
        got = m.version(name)
    except m.PackageNotFoundError:
        got = None
    if got is None or got.split("+")[0] != want:
        print(req)
PY
}
ensure() { # ensure [pip options --] req...
    local opts=()
    if [[ ${1:-} == --index-url ]]; then opts=("$1" "$2") && shift 2; fi
    local need
    need=$(outdated "$@")
    if [[ -z $need ]]; then
        echo "already at pinned versions: $*"
    else
        # ${opts[@]+...}: macOS bash 3.2 treats an empty array as unset under `set -u`.
        # shellcheck disable=SC2086
        pip_install ${opts[@]+"${opts[@]}"} $need
    fi
}
ensure "numpy==$NUMPY" "matplotlib==$MATPLOTLIB" "pytest==$PYTEST"
if want torch; then
    step "PyTorch $TORCH"
    if [[ $OS == linux ]]; then
        # The CUDA-specific index brings the matching triton as a dependency.
        ensure --index-url "$TORCH_INDEX" "torch==$TORCH"
    else
        ensure "torch==$TORCH" # macOS wheels on PyPI (CPU/MPS)
    fi
fi
if want hf; then
    step "Hugging Face tooling"
    ensure "transformers==$TRANSFORMERS" "safetensors==$SAFETENSORS" "huggingface_hub==$HF_HUB"
fi

if want cargo; then
    step "Rust $RUST"
    if [[ ! -x $HOME/.cargo/bin/rustup ]]; then
        curl --proto '=https' --tlsv1.2 -sSf https://sh.rustup.rs \
            | sh -s -- -y --profile minimal --default-toolchain "$RUST" --component clippy,rustfmt
    elif [[ $("$HOME/.cargo/bin/rustc" --version 2> /dev/null | awk '{ print $2 }') != "$RUST" ]]; then
        "$HOME/.cargo/bin/rustup" toolchain install "$RUST" --profile minimal --component clippy,rustfmt
        "$HOME/.cargo/bin/rustup" default "$RUST"
    else
        echo "already installed: rustc $RUST"
    fi
fi

step "shell setup ($RC)"
add_line "eval \"\$(direnv hook $SHELL_NAME)\""
add_line "alias mlsys='source $VENV/bin/activate'"
if [[ $OS == linux ]] && want cuda; then
    add_line 'export PATH=/usr/local/cuda/bin:$PATH'
    add_line 'export LD_LIBRARY_PATH=/usr/local/cuda/lib64:${LD_LIBRARY_PATH:-}'
fi
if want cargo; then add_line '. "$HOME/.cargo/env"'; fi
if [[ -n $MODEL_LIST ]]; then add_line "export MLSYS_MODELS=$MODELS"; fi
# .envrc puts the venv first on PATH inside this repo, so plain `python` and `python3`
# are the course interpreter. direnv refuses an .envrc until it is allowed.
if command -v direnv > /dev/null; then direnv allow "$LABS_ROOT/.."; fi
mkdir -p results/environment

if [[ -n $MODEL_LIST && $WITH_MODELS == 1 ]]; then
    step "models -> $MODELS"
    mkdir -p "$MODELS"
    for m in $MODEL_LIST; do
        if [[ -f $MODELS/$m/config.json && -f $MODELS/$m/tokenizer.json ]] \
            && compgen -G "$MODELS/$m/*.safetensors" > /dev/null; then
            echo "$m already present"
        else
            # Files already on disk are skipped. If huggingface.co is slow, first
            # `export HF_ENDPOINT=https://hf-mirror.com`.
            "$VENV/bin/hf" download "Qwen/$m" --local-dir "$MODELS/$m"
        fi
    done
elif [[ -n $MODEL_LIST ]]; then
    echo "skipped models (--no-models): $MODEL_LIST"
fi

{
    echo "$PINS_HASH  env-versions.env"
    grep -E '^[A-Z_][A-Z0-9_]*=' tools/env-versions.env | tr -d '\r'
} > "$STAMP"
step "done (pins $PINS_HASH recorded in $STAMP)."
echo "Open a NEW terminal, cd into the repo, then run:  bash tools/check_env.sh --lab $LAB"
