# Installs the native-Windows (CPU) part of ONE lab's environment, at the versions pinned in
# tools/env-versions.env. Labs are independent: -Lab N installs the base plus lab N only.
# PowerShell 5.1+ or 7. Run from labs\ (or anywhere; the script changes into labs\):
#   powershell -ExecutionPolicy Bypass -File tools\setup_env.ps1 -Lab 5
#   powershell -ExecutionPolicy Bypass -File tools\setup_env.ps1 -Lab 4 -NoModels
#   powershell -ExecutionPolicy Bypass -File tools\setup_env.ps1 -Lab all
#
# Native Windows is CPU-only in this course: CUDA stages print the WSL2 command instead.
# Safe to re-run: every step skips what is already there.
#   C++ toolchain -> existing cl.exe/g++, else MSYS2 UCRT64 (gcc, cmake, ninja) via winget
#                    under $env:MSYS2_ROOT (default: <system drive>\msys64)
#   Python        -> python.org 3.12 via winget, only if no Python 3.10+ is found
#   venv          -> %USERPROFILE%\venvs\mlsys (override with $env:MLSYS_VENV)
#   torch         -> CPU wheel at the TORCH pin from https://download.pytorch.org/whl/cpu
#   Rust          -> rustup at RUST (formatter-versions.env); gnu host when MSVC is absent
#   models        -> hf download into $env:MLSYS_MODELS (default %USERPROFILE%\models)
#   `mlsys`       -> a function in your PowerShell profile that activates the venv
param(
    [string]$Lab = '',
    [switch]$NoModels,
    [switch]$Repin
)

$ErrorActionPreference = 'Stop'
Set-Location (Join-Path $PSScriptRoot '..')
$LabsRoot = (Get-Location).Path

# BEGIN LAB TABLE (generated by: python tools/lab_meta.py --table; keep in sync)
$LabTable = @{
    1 = 'comps="gpu:R cuda:R" models=""'
    2 = 'comps="gpu cuda" models=""'
    3 = 'comps="gpu cuda torch" models=""'
    4 = 'comps="gpu:R torch:R hf:R cargo" models="Qwen3-0.6B:R Qwen3-1.7B:R"'
    5 = 'comps="gpu:R torch:R hf:R cargo" models="Qwen3-0.6B:R"'
    6 = 'comps="gpu torch" models=""'
    7 = 'comps="gpu cuda" models=""'
    8 = 'comps="cargo" models=""'
    9 = 'comps="gpu:R cuda:R" models=""'
}
# END LAB TABLE

function Usage {
    Write-Host 'usage: tools\setup_env.ps1 -Lab N|all [-NoModels] [-Repin]   (N = 1-9)'
    exit 2
}
if (-not $Lab) { Usage }
if ($Lab -eq 'all') { $labs = @($LabTable.Keys | Sort-Object) }
elseif ($Lab -match '^\d+$' -and $LabTable.ContainsKey([int]$Lab)) { $labs = @([int]$Lab) }
else { Usage }

$components = New-Object System.Collections.Generic.List[string]
$modelList = New-Object System.Collections.Generic.List[string]
foreach ($n in $labs) {
    $null = $LabTable[$n] -match 'comps="([^"]*)" models="([^"]*)"'
    foreach ($c in ($Matches[1] -split ' ' | Where-Object { $_ })) {
        $c = $c -replace ':R$', ''
        if (-not $components.Contains($c)) { $components.Add($c) }
    }
    foreach ($m in ($Matches[2] -split ' ' | Where-Object { $_ })) {
        $m = $m -replace ':R$', ''
        if (-not $modelList.Contains($m)) { $modelList.Add($m) }
    }
}
function Want([string]$Component) { $components.Contains($Component) }

$pins = @{}
foreach ($file in 'tools\env-versions.env', 'tools\formatter-versions.env') {
    Get-Content $file | Where-Object { $_ -match '^[A-Z_][A-Z0-9_]*=' } | ForEach-Object {
        $key, $value = $_ -split '=', 2
        if ($file -like '*env-versions*' -or $key -eq 'RUST') { $pins[$key] = $value.Trim() }
    }
}
$pinLines = @(Get-Content 'tools\env-versions.env' | Where-Object { $_ -match '^[A-Z_][A-Z0-9_]*=' })
$sha = [System.Security.Cryptography.SHA256]::Create()
$bytes = [System.Text.Encoding]::UTF8.GetBytes((($pinLines | ForEach-Object { "$_`n" }) -join ''))
$PinsHash = -join ($sha.ComputeHash($bytes) | ForEach-Object { $_.ToString('x2') })

$Venv = if ($env:MLSYS_VENV) { $env:MLSYS_VENV } else { Join-Path $HOME 'venvs\mlsys' }
$VenvPy = Join-Path $Venv 'Scripts\python.exe'
$Models = if ($env:MLSYS_MODELS) { $env:MLSYS_MODELS } else { Join-Path $HOME 'models' }
$Msys = if ($env:MSYS2_ROOT) { $env:MSYS2_ROOT } else { Join-Path $env:SystemDrive 'msys64' }
$Stamp = Join-Path $Venv '.mlsys-pins'

function Step([string]$Text) {
    Write-Host ''
    Write-Host "==> $Text" -ForegroundColor Cyan
}
function Have([string]$Exe) { [bool](Get-Command $Exe -ErrorAction SilentlyContinue) }
function Need-Winget([string]$What) {
    if (-not (Have 'winget')) {
        throw "winget not found. Install $What by hand (see setup.md), open a new terminal and re-run."
    }
}
function Wsl-Path([string]$Path) {
    if ($Path -match '^([A-Za-z]):[\\/]?(.*)$') {
        return '/mnt/' + $Matches[1].ToLower() + '/' + ($Matches[2] -replace '\\', '/')
    }
    return $Path -replace '\\', '/'
}

# Returns the launcher and its leading arguments, e.g. @('py', '-3.12'). The
# Microsoft Store stubs `python`/`python3` fail the version check and are skipped.
function Find-Python {
    $candidates = @(
        @('py', '-3.14'), @('py', '-3.13'), @('py', '-3.12'), @('py', '-3.11'), @('py', '-3.10'),
        @('python'), @((Join-Path $env:LOCALAPPDATA 'Programs\Python\Python312\python.exe'))
    )
    foreach ($cand in $candidates) {
        if (-not (Have $cand[0])) { continue }
        $source = (Get-Command $cand[0]).Source
        if ($source -like '*\WindowsApps\*') { continue } # Store stub
        $rest = @($cand | Select-Object -Skip 1)
        & $cand[0] @rest -c 'import sys; sys.exit(0 if sys.version_info >= (3, 10) else 1)' 2>$null
        if ($LASTEXITCODE -eq 0) { return ,$cand } # the comma keeps @('python') an array
    }
    return $null
}

# True when MSVC's C++ tools are installed (cl.exe/link.exe), found via vswhere.
function Have-Msvc {
    if (Have 'cl') { return $true }
    $vswhere = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio\Installer\vswhere.exe'
    if (-not (Test-Path $vswhere)) { return $false }
    $path = & $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath 2>$null
    return [bool]$path
}

Write-Host "lab: $Lab   components: $($components -join ' ')   models: $(if ($modelList.Count) { $modelList -join ' ' } else { 'none' })"
foreach ($n in $labs) {
    if (-not (Test-Path "lab$n\exercise.py")) {
        Write-Host "note: lab$n is registered in tools\lab_meta.py but labs\lab$n does not exist yet."
    }
}
if ((Want 'cuda') -or (Want 'gpu')) {
    $target = Wsl-Path $LabsRoot
    Write-Host "Native Windows is CPU-only here: the CUDA stages of lab $Lab run in WSL2. Set them up with:"
    Write-Host "    wsl -d Ubuntu-24.04 -- bash -lc `"cd '$target' && bash tools/setup_env.sh --lab $Lab`""
    Write-Host 'The CPU parts are installed below.'
}

if ((Test-Path $Stamp) -and -not $Repin) {
    $old = ((Get-Content $Stamp -TotalCount 1) -split ' ')[0]
    if ($old -ne $PinsHash) {
        Write-Host "The venv $Venv was set up with different pins (hash in $Stamp)."
        Write-Host 'Align tools\env-versions.env, set $env:MLSYS_VENV to another venv, or re-run with -Repin.'
        exit 1
    }
}

Step 'C++ toolchain'
if (Have 'cl') {
    Write-Host "MSVC on PATH: $((Get-Command cl).Source) (tools pick cl first)"
} elseif ((Have 'g++') -and (Have 'cmake')) {
    Write-Host "g++ on PATH: $((Get-Command g++).Source) (MinGW family; MSVC is used instead from a Developer terminal)"
} else {
    if (-not (Test-Path (Join-Path $Msys 'usr\bin\bash.exe'))) {
        Need-Winget 'MSYS2 (https://www.msys2.org)'
        $location = @()
        if ($env:MSYS2_ROOT) { $location = @('--location', $Msys) }
        winget install --id MSYS2.MSYS2 -e @location --accept-source-agreements --accept-package-agreements
        if ($LASTEXITCODE -ne 0) { throw 'winget install MSYS2 failed' }
    }
    & (Join-Path $Msys 'usr\bin\bash.exe') -lc 'pacman -S --needed --noconfirm mingw-w64-ucrt-x86_64-gcc mingw-w64-ucrt-x86_64-cmake mingw-w64-ucrt-x86_64-ninja'
    if ($LASTEXITCODE -ne 0) { throw 'pacman failed' }
    $bin = Join-Path $Msys 'ucrt64\bin'
    $userPath = [Environment]::GetEnvironmentVariable('Path', 'User')
    if (($userPath -split ';') -notcontains $bin) {
        [Environment]::SetEnvironmentVariable('Path', "$bin;$userPath", 'User')
        Write-Host "added $bin to your user PATH"
    }
    $env:Path = "$bin;$env:Path"
    Write-Host "MSYS2 UCRT64 g++: $bin\g++.exe (MinGW family)"
}
if (-not ($LabsRoot -match '^[\x00-\x7F]*$')) {
    Write-Host "WARNING: $LabsRoot contains non-ASCII characters; MinGW ld is known to fail there. Use an ASCII path, MSVC or WSL."
}

Step "Python venv at $Venv"
if (-not (Test-Path $VenvPy)) {
    $py = Find-Python
    if (-not $py) {
        Need-Winget 'Python 3.12 (https://www.python.org/downloads/windows/)'
        winget install --id Python.Python.3.12 -e --scope user --accept-source-agreements --accept-package-agreements
        if ($LASTEXITCODE -ne 0) { throw 'winget install Python failed' }
        $py = Find-Python
        if (-not $py) { throw 'Python was installed; open a new terminal and re-run this script.' }
    }
    $pyRest = @($py | Select-Object -Skip 1)
    New-Item -ItemType Directory -Force (Split-Path $Venv) | Out-Null
    & $py[0] @pyRest -m venv $Venv
    if ($LASTEXITCODE -ne 0) { throw "failed to create $Venv" }
    & $VenvPy -m pip install -q --upgrade pip
}

# Installs only the requirements whose installed version differs from the pin.
function Ensure([string[]]$Requirements, [string[]]$PipOptions = @()) {
    $probe = 'import importlib.metadata as m, sys' + "`n" +
        'for r in sys.argv[1:]:' + "`n" +
        '    n, w = r.split("==")' + "`n" +
        '    try: g = m.version(n)' + "`n" +
        '    except m.PackageNotFoundError: g = None' + "`n" +
        '    if g is None or g.split("+")[0] != w: print(r)'
    $need = @(& $VenvPy -c $probe @Requirements | Where-Object { $_ })
    if ($need.Count -eq 0) {
        Write-Host "already at pinned versions: $($Requirements -join ' ')"
        return
    }
    & $VenvPy -m pip install --disable-pip-version-check @PipOptions @need
    if ($LASTEXITCODE -ne 0) { throw "pip install failed: $($need -join ' ')" }
}
Ensure @("numpy==$($pins['NUMPY'])", "matplotlib==$($pins['MATPLOTLIB'])", "pytest==$($pins['PYTEST'])")
# Windows venvs only have python.exe; the copy makes `python3 ...` reach the venv instead
# of the Microsoft Store stub once the venv is activated.
Copy-Item $VenvPy (Join-Path $Venv 'Scripts\python3.exe') -Force

if (Want 'torch') {
    Step "PyTorch $($pins['TORCH']) (CPU wheel)"
    Ensure @("torch==$($pins['TORCH'])") @('--index-url', 'https://download.pytorch.org/whl/cpu')
}
if (Want 'hf') {
    Step 'Hugging Face tooling'
    Ensure @("transformers==$($pins['TRANSFORMERS'])", "safetensors==$($pins['SAFETENSORS'])", "huggingface_hub==$($pins['HF_HUB'])")
}

if (Want 'cargo') {
    $rust = $pins['RUST']
    Step "Rust $rust"
    $cargoBin = Join-Path $HOME '.cargo\bin'
    $rustup = Join-Path $cargoBin 'rustup.exe'
    if (-not (Test-Path $rustup)) {
        $hostTriple = if (Have-Msvc) { 'x86_64-pc-windows-msvc' } else { 'x86_64-pc-windows-gnu' }
        Write-Host "installing rustup with host $hostTriple"
        $init = Join-Path ([System.IO.Path]::GetTempPath()) 'rustup-init.exe'
        Invoke-WebRequest -UseBasicParsing -Uri 'https://win.rustup.rs/x86_64' -OutFile $init
        & $init -y --profile minimal --default-host $hostTriple --default-toolchain $rust --component clippy,rustfmt
        if ($LASTEXITCODE -ne 0) { throw 'rustup-init failed' }
        Remove-Item $init -Force
    } else {
        $got = (& (Join-Path $cargoBin 'rustc.exe') --version 2>$null) -split ' '
        if ($got.Count -lt 2 -or $got[1] -ne $rust) {
            & $rustup toolchain install $rust --profile minimal --component clippy,rustfmt
            & $rustup default $rust
        } else {
            Write-Host "already installed: rustc $rust"
        }
    }
    if (($env:Path -split ';') -notcontains $cargoBin) { $env:Path = "$cargoBin;$env:Path" }
}

Step "PowerShell profile ($($PROFILE.CurrentUserAllHosts))"
# Activate.ps1 and the profile are scripts; the default policy (Restricted) blocks both.
$policy = Get-ExecutionPolicy -Scope CurrentUser
if ($policy -eq 'Undefined' -or $policy -eq 'Restricted' -or $policy -eq 'AllSigned') {
    Set-ExecutionPolicy -Scope CurrentUser RemoteSigned -Force
    Write-Host 'set execution policy for your user to RemoteSigned (needed to activate a venv)'
}
$line = "function mlsys { & '$Venv\Scripts\Activate.ps1' }"
$profilePath = $PROFILE.CurrentUserAllHosts
if (-not (Test-Path $profilePath)) { New-Item -ItemType File -Force $profilePath | Out-Null }
if (-not (Select-String -Path $profilePath -SimpleMatch $line -Quiet)) {
    Add-Content -Path $profilePath -Value $line
    Write-Host 'added the `mlsys` command'
} else {
    Write-Host '`mlsys` command already present'
}
New-Item -ItemType Directory -Force (Join-Path $LabsRoot 'results\environment') | Out-Null

if ($modelList.Count -gt 0 -and -not $NoModels) {
    Step "models -> $Models"
    New-Item -ItemType Directory -Force $Models | Out-Null
    foreach ($m in $modelList) {
        $dir = Join-Path $Models $m
        $complete = (Test-Path (Join-Path $dir 'config.json')) -and (Test-Path (Join-Path $dir 'tokenizer.json')) -and
            [bool](Get-ChildItem -Path $dir -Filter '*.safetensors' -ErrorAction SilentlyContinue)
        if ($complete) {
            Write-Host "$m already present"
        } else {
            # If huggingface.co is slow, first: $env:HF_ENDPOINT = 'https://hf-mirror.com'
            & (Join-Path $Venv 'Scripts\hf.exe') download "Qwen/$m" --local-dir $dir
            if ($LASTEXITCODE -ne 0) { throw "hf download Qwen/$m failed" }
        }
    }
} elseif ($modelList.Count -gt 0) {
    Write-Host "skipped models (-NoModels): $($modelList -join ' ')"
}

$stampText = (@("$PinsHash  env-versions.env") + $pinLines) -join "`n"
[System.IO.File]::WriteAllText($Stamp, "$stampText`n", (New-Object System.Text.UTF8Encoding $false))
Step "done (pins $PinsHash recorded in $Stamp)."
Write-Host "Open a NEW terminal, cd into labs\, run ``mlsys``, then:  powershell -ExecutionPolicy Bypass -File tools\check_env.ps1 -Lab $Lab"
