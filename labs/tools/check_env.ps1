# The native-Windows (CPU) environment verdict for one lab, one line per item.
#   powershell -ExecutionPolicy Bypass -File tools\check_env.ps1 -Lab 5     # only what lab5 needs
#   powershell -ExecutionPolicy Bypass -File tools\check_env.ps1            # every lab
# [ OK ] works   [WARN] usable but differs from the pins / only needed by stage R
# [FAIL] required and broken (a `fix:` line follows)   [ -- ] optional or not on Windows
# Exit code: 0 no FAIL, 1 at least one FAIL, 2 usage error.
# CUDA stages are not checked here: they run in WSL2 (tools/check_env.sh).
param([string]$Lab = 'all')

Set-Location (Join-Path $PSScriptRoot '..')
$LabsRoot = (Get-Location).Path

# BEGIN LAB TABLE (generated by: python tools/lab_meta.py --table; keep in sync)
$LabTable = @{
    1 = 'comps="gpu:R cuda:R" models=""'
    2 = 'comps="gpu cuda" models=""'
    3 = 'comps="gpu cuda torch" models=""'
    4 = 'comps="gpu:R torch:R hf:R cargo" models="Qwen3-0.6B:R Qwen3-1.7B:R"'
    5 = 'comps="gpu:R torch:R hf:R cargo" models="Qwen3-0.6B:R"'
    6 = 'comps="gpu torch" models=""'
    7 = 'comps="gpu cuda" models=""'
    8 = 'comps="cargo" models=""'
    9 = 'comps="gpu:R cuda:R" models=""'
}
# END LAB TABLE

if ($Lab -eq 'all') { $labs = @($LabTable.Keys | Sort-Object) }
elseif ($Lab -match '^\d+$' -and $LabTable.ContainsKey([int]$Lab)) { $labs = @([int]$Lab) }
else {
    Write-Host 'usage: tools\check_env.ps1 [-Lab N|all]   (N = 1-9)'
    exit 2
}

# Level per component/model: 'req' if any selected lab needs it outside stage R, else 'soft'.
$level = @{}
$modelLevel = [ordered]@{}
foreach ($n in $labs) {
    $null = $LabTable[$n] -match 'comps="([^"]*)" models="([^"]*)"'
    $comps, $mods = $Matches[1], $Matches[2]
    foreach ($c in ($comps -split ' ' | Where-Object { $_ })) {
        $key = $c -replace ':R$', ''
        $l = if ($c -like '*:R') { 'soft' } else { 'req' }
        if ($level[$key] -ne 'req') { $level[$key] = $l }
    }
    foreach ($m in ($mods -split ' ' | Where-Object { $_ })) {
        $key = $m -replace ':R$', ''
        $l = if ($m -like '*:R') { 'soft' } else { 'req' }
        if ($modelLevel[$key] -ne 'req') { $modelLevel[$key] = $l }
    }
}

$pins = @{}
Get-Content 'tools\env-versions.env' | Where-Object { $_ -match '^[A-Z_][A-Z0-9_]*=' } | ForEach-Object {
    $key, $value = $_ -split '=', 2
    $pins[$key] = $value.Trim()
}
$rustLine = Get-Content 'tools\formatter-versions.env' | Where-Object { $_ -match '^RUST=' } | Select-Object -First 1
$pins['RUST'] = ($rustLine -split '=', 2)[1].Trim()
$Venv = if ($env:MLSYS_VENV) { $env:MLSYS_VENV } else { Join-Path $HOME 'venvs\mlsys' }
$VenvPy = Join-Path $Venv 'Scripts\python.exe'
$Models = if ($env:MLSYS_MODELS) { $env:MLSYS_MODELS } else { Join-Path $HOME 'models' }
$Fix = "powershell -ExecutionPolicy Bypass -File tools\setup_env.ps1 -Lab $Lab"
$script:Fail = $false
$script:Warns = 0

function Ok([string]$Name, [string]$Msg) { Write-Host ('  [ OK ]  {0,-20} {1}' -f $Name, $Msg) }
function Warn([string]$Name, [string]$Msg, [string]$How = '') {
    Write-Host ('  [WARN]  {0,-20} {1}' -f $Name, $Msg)
    if ($How) { Write-Host ('          {0,-20} fix: {1}' -f '', $How) }
    $script:Warns++
}
function Bad([string]$Name, [string]$Msg, [string]$How = $Fix) {
    Write-Host ('  [FAIL]  {0,-20} {1}' -f $Name, $Msg)
    Write-Host ('          {0,-20} fix: {1}' -f '', $How)
    $script:Fail = $true
}
function Opt([string]$Name, [string]$Msg) { Write-Host ('  [ -- ]  {0,-20} {1}' -f $Name, $Msg) }
function Report([string]$Level, [string]$Name, [string]$Msg, [string]$How = $Fix) {
    if ($Level -eq 'req') { Bad $Name $Msg $How }
    elseif ($Level -eq 'soft') { Warn $Name "$Msg (only stage R needs it)" $How }
    else { Opt $Name $Msg }
}
function Wsl-Path([string]$Path) {
    if ($Path -match '^([A-Za-z]):[\\/]?(.*)$') {
        return '/mnt/' + $Matches[1].ToLower() + '/' + ($Matches[2] -replace '\\', '/')
    }
    return $Path -replace '\\', '/'
}
# Runs the venv interpreter; returns @(exitcode, last output line).
function Py([string[]]$Arguments) {
    if (-not (Test-Path $VenvPy)) { return @(1, "venv $Venv does not exist") }
    $out = & $VenvPy @Arguments 2>&1 | ForEach-Object { "$_" }
    $code = $LASTEXITCODE
    $last = @($out | Where-Object { $_ -and $_.Trim() }) | Select-Object -Last 1
    return @($code, "$last")
}
function Check-Package([string]$Level, [string]$Name, [string]$Dist, [string]$Pinned) {
    $r = Py @('-c', "import importlib.metadata as m; print(m.version('$Dist'))")
    if ($r[0] -ne 0) { Report $Level $Name "not installed in $Venv"; return }
    $got = $r[1].Trim()
    if ($got -eq $Pinned -or $got.StartsWith("$Pinned+")) { Ok $Name $got }
    else { Warn $Name "$got (pinned $Pinned)" "$Fix -Repin" }
}

Write-Host "== lab $Lab environment (Windows, venv $Venv)"
Ok 'platform' "windows ($([Environment]::OSVersion.VersionString)); native Windows is CPU-only"
foreach ($n in $labs) {
    if (-not (Test-Path "lab$n\exercise.py")) { Opt "lab$n" "registered in tools\lab_meta.py; labs\lab$n not in this checkout yet" }
}

# python / python3 must be the venv (the usual failure: the Microsoft Store stub).
foreach ($exe in 'python', 'python3') {
    $cmd = Get-Command $exe -ErrorAction SilentlyContinue
    $got = if ($cmd) { $cmd.Source } else { 'not found' }
    if ($got -like "$Venv\Scripts\*") { Ok "$exe on PATH" $got }
    elseif (Test-Path $VenvPy) { Bad "$exe on PATH" "$got is not the course venv" 'run: mlsys   (activates the venv in this terminal; or open a new terminal)' }
    else { Bad "$exe on PATH" "venv $Venv does not exist" }
}
Check-Package 'req' 'numpy' 'numpy' $pins['NUMPY']
Check-Package 'req' 'matplotlib' 'matplotlib' $pins['MATPLOTLIB']
Check-Package 'req' 'pytest' 'pytest' $pins['PYTEST']

# Pins stamp written by setup_env, and drift against a sibling mlsys-foundations checkout.
$pinLines = @(Get-Content 'tools\env-versions.env' | Where-Object { $_ -match '^[A-Z_][A-Z0-9_]*=' })
$sha = [System.Security.Cryptography.SHA256]::Create()
$bytes = [System.Text.Encoding]::UTF8.GetBytes((($pinLines | ForEach-Object { "$_`n" }) -join ''))
$want = -join ($sha.ComputeHash($bytes) | ForEach-Object { $_.ToString('x2') })
$stamp = Join-Path $Venv '.mlsys-pins'
if (-not (Test-Path $stamp)) { Warn 'pins stamp' "$stamp missing (venv not created by setup_env)" $Fix }
else {
    $got = ((Get-Content $stamp -TotalCount 1) -split ' ')[0]
    if ($got -eq $want) { Ok 'pins stamp' "$($want.Substring(0, 16)) matches tools\env-versions.env" }
    else { Warn 'pins stamp' "venv pinned $($got.Substring(0, [Math]::Min(16, $got.Length))), this checkout $($want.Substring(0, 16))" "$Fix -Repin" }
}
$sibling = Join-Path $LabsRoot '..\..\mlsys-foundations\labs\tools\env-versions.env'
if (Test-Path $sibling) {
    $other = @(Get-Content $sibling | Where-Object { $_ -match '^[A-Z_][A-Z0-9_]*=' })
    if (($other -join "`n") -eq ($pinLines -join "`n")) { Ok 'foundations pins' 'same as ..\mlsys-foundations (shared venv is consistent)' }
    else { Warn 'foundations pins' '..\mlsys-foundations pins differ; the shared venv fits only one' 'align both env-versions.env files, or set $env:MLSYS_VENV per repository' }
} else { Opt 'foundations pins' 'no sibling ..\mlsys-foundations checkout' }

# C++17: compile and run a hello program with the compiler the lab tools would pick.
$cxx = $null
if ($env:CXX) { $cxx = Get-Command $env:CXX.Trim('"') -ErrorAction SilentlyContinue }
if (-not $cxx) { foreach ($c in 'cl', 'clang++', 'g++', 'c++') { $cxx = Get-Command $c -ErrorAction SilentlyContinue; if ($cxx) { break } } }
if (-not $cxx) {
    Bad 'C++17 compiler' 'no cl/clang++/g++ on PATH'
} else {
    $tmp = Join-Path ([System.IO.Path]::GetTempPath()) ("mlsys-check-" + [guid]::NewGuid().ToString('N'))
    New-Item -ItemType Directory -Force $tmp | Out-Null
    $src = Join-Path $tmp 'hello.cpp'
    $exe = Join-Path $tmp 'hello.exe'
    Set-Content -Path $src -Encoding ascii -Value '#include <cstdio>', '#include <optional>', 'int main() { std::optional<int> x = 17; std::printf("C++%d ok\n", *x); }'
    $isMsvc = $cxx.Name -match '^cl(\.exe)?$'
    if ($isMsvc) {
        $family = 'msvc'
        $null = & $cxx.Source /nologo /std:c++17 /EHsc "/Fe$exe" "/Fo$tmp\" $src 2>&1
    } else {
        $ver = (& $cxx.Source --version 2>&1 | Select-Object -First 1)
        $family = if ("$ver" -match 'clang') { 'mingw-clang' } else { 'mingw-gcc' }
        $null = & $cxx.Source -std=c++17 -O2 $src -o $exe 2>&1
    }
    if ($LASTEXITCODE -eq 0 -and (Test-Path $exe)) {
        $out = & $exe
        Ok 'C++17 compiler' "$out`: $($cxx.Source) ($family)"
    } else {
        Bad 'C++17 compiler' "$($cxx.Source) ($family) failed to build a C++17 program"
    }
    Remove-Item -Recurse -Force $tmp -ErrorAction SilentlyContinue
    if ($family -like 'mingw*' -and -not ("$LabsRoot$([System.IO.Path]::GetTempPath())" -match '^[\x00-\x7F]*$')) {
        Warn 'MinGW + path' 'repository or TEMP path is non-ASCII; MinGW ld is known to fail there' 'use an ASCII path, an x64 Developer PowerShell (MSVC), or WSL'
    }
}
if (Get-Command cmake -ErrorAction SilentlyContinue) { Ok 'cmake' "$(& cmake --version | Select-Object -First 1)" } else { Opt 'cmake' 'not on PATH (optional)' }

if ($level.ContainsKey('gpu') -or $level.ContainsKey('cuda')) {
    $target = Wsl-Path $LabsRoot
    Opt 'CUDA' "CUDA stages run in WSL2: wsl -d Ubuntu-24.04 -- bash -lc `"cd '$target' && bash tools/check_env.sh --lab $Lab`""
}
if ($level.ContainsKey('torch')) {
    Check-Package $level['torch'] 'torch' 'torch' $pins['TORCH']
    $r = Py @('-c', 'import torch; x = torch.randn(64, 64); print("cpu matmul ok", float((x @ x).sum()) == float((x @ x).sum()))')
    if ($r[0] -eq 0) { Ok 'torch (cpu)' $r[1] } else { Report $level['torch'] 'torch (cpu)' $r[1] }
}
if ($labs -contains 3) {
    $r = Py @('tools\doctor.py', '--compile-probe', '--device', 'cpu')
    if ($r[0] -eq 0) { Ok 'Inductor (cpu)' $r[1] }
    else { Bad 'Inductor (cpu)' $r[1] 'Inductor on Windows needs MSVC (x64 Developer PowerShell); otherwise run lab3 C in WSL' }
}
if ($level.ContainsKey('hf')) {
    Check-Package $level['hf'] 'transformers' 'transformers' $pins['TRANSFORMERS']
    Check-Package $level['hf'] 'safetensors' 'safetensors' $pins['SAFETENSORS']
    Check-Package $level['hf'] 'huggingface_hub' 'huggingface_hub' $pins['HF_HUB']
}
if ($level.ContainsKey('cargo')) {
    $cargo = Get-Command cargo -ErrorAction SilentlyContinue
    $cargoPath = if ($cargo) { $cargo.Source } else { Join-Path $HOME '.cargo\bin\cargo.exe' }
    if (Test-Path $cargoPath) {
        $rustc = Join-Path (Split-Path $cargoPath) 'rustc.exe'
        $cv = & $cargoPath --version 2>&1 | Select-Object -First 1
        $rv = & $rustc --version 2>&1 | Select-Object -First 1
        if ("$rv" -like "rustc $($pins['RUST']) *") { Ok 'cargo / rustc' "$cv / $rv" }
        else { Warn 'cargo / rustc' "$cv / $rv (pinned $($pins['RUST']))" $Fix }
    } else {
        Bad 'cargo / rustc' 'cargo not found (also looked in ~\.cargo\bin)'
    }
}
foreach ($m in $modelLevel.Keys) {
    $dir = Join-Path $Models $m
    $weights = @(Get-ChildItem -Path $dir -Filter '*.safetensors' -ErrorAction SilentlyContinue)
    if ((Test-Path (Join-Path $dir 'config.json')) -and (Test-Path (Join-Path $dir 'tokenizer.json')) -and $weights.Count -gt 0) {
        $gib = ($weights | Measure-Object -Property Length -Sum).Sum / 1GB
        Ok $m ('{0:N2} GiB in {1}' -f $gib, $dir)
    } else {
        Report $modelLevel[$m] $m "incomplete or missing in $dir (config.json, tokenizer.json, *.safetensors)"
    }
}

Write-Host ''
if ($script:Fail) {
    Write-Host 'Some required items FAILED (fix commands above).'
    exit 1
}
if ($script:Warns -gt 0) { Write-Host "All required items OK ($($script:Warns) warning(s): see [WARN] lines)." }
else { Write-Host 'All required items OK.' }
exit 0
